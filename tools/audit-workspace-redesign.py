"""Inventory actual redesign scope and completed local browser evidence; run at repo root."""
import json
import re
from pathlib import Path

app = Path('InternshipManagementSystem/InternshipManagementSystem')
artifacts = Path('tests/artifacts')
results = {}
for name in ('workspace', 'routes', 'workflows', 'offers', 'actions', 'contracts', 'motion', 'after'):
    path = artifacts / f'redesign-{name}.txt'
    text = path.read_text(encoding='utf-8-sig') if path.exists() else ''
    match = re.search(r'^### Result\s*\n(\{[^\n]+\})', text, re.M)
    if not match:
        raise SystemExit(f'No completed result: {path}')
    results[name] = json.loads(match.group(1))
    (artifacts / f'redesign-{name}-results.json').write_text(json.dumps(results[name], indent=2) + '\n', encoding='utf-8')

routes = []
for path in sorted(app.rglob('*.aspx')):
    if any(part in ('bin', 'obj') for part in path.parts):
        continue
    route = path.relative_to(app).as_posix()
    text = path.read_text(encoding='utf-8-sig', errors='replace')
    master = re.search(r'MasterPageFile="([^"]+)', text)
    role = path.parent.name
    recomposed = path.name == 'Dashboard.aspx' and role in ('Student', 'Company', 'Academic', 'Coordinator')
    scope = 'Dashboard recomposed + interactive role journey' if recomposed else ('Shared public refinement; original scene preserved' if role == 'Public' or route in ('Default.aspx', 'Pages/Account/Login.aspx') else 'Shared shell/type/controls refinement; existing composition')
    if path.name in ('ApplicantDocument.aspx', 'CompletionReport.aspx'):
        scope = 'Document authorization negative check; no visual redesign'
    if path.name == 'exploreOpport.aspx':
        scope = 'Existing bookmark redirect; refined target Opportunities.aspx'
    visits = [r for r in results['routes']['routes'] if r['route'].split('?')[0] == route]
    routes.append({'route': route, 'master': master.group(1) if master else 'dynamic/endpoint', 'scope': scope, 'runtime': visits,
                   'pageLocalActions': len(re.findall(r'data-ui-action=', text)), 'journey': recomposed})
out = {'date': '2026-10-23', 'environment': 'Disposable ASP.NET Web Forms copy + local Postman dependencies only',
       'routeCount': len(routes), 'recomposedDashboards': 4, 'visits': len(results['routes']['routes']), 'routes': routes,
       'checks': {key: value.get('passed') for key, value in results.items() if 'passed' in value}}
Path('docs/workspace-redesign-coverage.json').write_text(json.dumps(out, indent=2) + '\n', encoding='utf-8')
lines = ['# Workspace redesign coverage', '', 'Generated by `python tools/audit-workspace-redesign.py`. Four dashboards were recomposed. Other pages receive the shared visual system; they are not claimed as individually redesigned.', '',
         '| Route | Implemented scope | Actual local fixture visits |', '| --- | --- | --- |']
for row in routes:
    widths = ', '.join(str(w) for w in sorted({v['width'] for v in row['runtime']}))
    evidence = widths + ' px' if widths else 'NOT VISITED'
    if any(v.get('kind') for v in row['runtime']):
        evidence = 'Document authorization negative check'
    lines.append(f"| `{row['route']}` | {row['scope']} | {evidence} |")
lines += ['', 'Shared components: five master layouts; 48px control language; outline SVG icons; ASP.NET validation and native uploads; status feedback; existing Bootstrap/custom dialog enhancement; new server-rendered WorkspaceJourney.ascx used by all four dashboards.', '',
          'The journey is a shared user control, not an additional route. Private evaluation reads remain server-side. Source inventory and route rendering do not certify every possible mutation or account combination.']
Path('docs/30-workspace-redesign-coverage.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(json.dumps({key: out[key] for key in ('routeCount', 'recomposedDashboards', 'visits', 'checks')}))
