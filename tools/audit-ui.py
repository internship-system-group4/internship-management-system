"""Read-only route/component inventory. Run from repository root."""
import json
import re
from collections import Counter
from pathlib import Path

root = Path('InternshipManagementSystem/InternshipManagementSystem')
runtime_file = Path('tests/artifacts/ui-system-results.json')
runtime = json.loads(runtime_file.read_text(encoding='utf-8')) if runtime_file.exists() else {}
rows = []
for path in sorted(root.rglob('*.aspx')):
    if any(part in ('obj', 'bin') for part in path.parts):
        continue
    text = path.read_text(encoding='utf-8-sig', errors='replace')
    master = re.search(r'MasterPageFile="([^"]+)', text)
    route = path.relative_to(root).as_posix()
    visits = [r for r in runtime.get('routes', []) if r['route'].split('?')[0] == route]
    row = {
        'route': route,
        'master': master.group(1) if master else 'dynamic role master',
        'serverActions': len(re.findall(r'<asp:(?:Button|LinkButton)\b', text, re.I)),
        'busyActions': len(re.findall(r'data-ui-action=', text)),
        'fields': len(re.findall(r'<asp:(?:TextBox|DropDownList|FileUpload)\b', text, re.I)),
        'tables': len(re.findall(r'<(?:table|asp:GridView)\b', text, re.I)),
        'dialogs': len(re.findall(r'class="(?:modal |modal")', text)),
        'updatePanels': len(re.findall(r'<asp:UpdatePanel\b', text, re.I)),
        'foundation': ('legacy bookmark redirects to Student/Opportunities.aspx' if path.name == 'exploreOpport.aspx'
                       else 'inherited through shared master; direct/binary responses have no controls'),
        'runtime': [{'width': v['width'], 'status': v['status'], 'url': v.get('url'),
                     'kind': v.get('kind', 'rendered fixture page'), 'overflow': v.get('overflow')} for v in visits],
    }
    rows.append(row)
summary = {'routeCount': len(rows), 'masters': dict(Counter(r['master'] for r in rows)),
           'totals': {k: sum(r[k] for r in rows) for k in ('serverActions', 'busyActions', 'fields', 'tables', 'dialogs', 'updatePanels')}}
out = Path('docs/ui-coverage.json')
out.write_text(json.dumps({'summary': summary, 'routes': rows}, indent=2) + '\n', encoding='utf-8')
lines = ['# UIMS route and component coverage', '',
         'Generated by `python tools/audit-ui.py`. Source inventory is not a claim that every business mutation was tested.', '',
         '| Route | Shared master | ASP actions / busy hooks | Fields | Tables | Bootstrap dialogs | Runtime fixture evidence |',
         '| --- | --- | ---: | ---: | ---: | ---: | --- |']
for row in rows:
    visits = row['runtime']
    evidence = ', '.join(str(v) for v in sorted({v['width'] for v in visits})) + ' px' if visits else 'not run'
    if visits and any(v['kind'] != 'rendered fixture page' for v in visits):
        evidence = 'document authorization negative check'
    elif row['route'].endswith('exploreOpport.aspx') and visits:
        evidence += '; redirect to current student opportunities'
    lines.append(f"| `{row['route']}` | `{row['master']}` | {row['serverActions']} / {row['busyActions']} | {row['fields']} | {row['tables']} | {row['dialogs']} | {evidence} |")
lines += ['', 'All five masters load ui-tokens.css, ui-system.css, and ui-system.js. '
          'Meetings and Notifications select a permitted role master on the server. '
          'Existing public form controllers own Login/recovery/contact loading and validation. '
          'Navigation, searches, dialog openers, downloads, and client-only notices intentionally do not acquire mutation busy hooks. '
          'No UpdatePanel exists in the current route inventory; the shared adapter supports the Microsoft AJAX lifecycle when present.', '',
          'Busy hooks include audited native submit buttons as well as ASP controls; they are not intended to cover searches, navigation or every ASP action. '
          'The dialog count is Bootstrap markup; three additional custom dialogs receive explicit accessibility/motion adapters. '
          'Runtime evidence proves page rendering and the named representative workflows, not every row command or permission permutation.', '']
Path('docs/26-ui-coverage.md').write_text('\n'.join(lines), encoding='utf-8')
print(json.dumps(summary))
