// Uses the real Web Forms page against the local Firebase Postman simulation.
// Seeds and resets synthetic data; use only a disposable host with cache disabled.
async page => {
 const base=new URL(page.url()).origin, db='http://localhost:4920/firebase',checks=[];
 await page.request.post(db+'/__reset');
 for(let i=0;i<12;i++){
  const id='perf-student-'+i;
  await page.request.put(db+'/users/'+id+'.json',{data:{Id:id,FullName:'Candidate '+i,Email:'candidate'+i+'@example.com',Role:1,IsActive:true,Major:'Computer Science',StudentNumber:'N'+i}});
  await page.request.put(db+'/studentProfileExtras/'+id+'.json',{data:{TechnicalSkills:'C#, testing',SoftSkills:'Teamwork'}});
  await page.request.put(db+'/applications/perf-app-'+i+'.json',{data:{Id:'perf-app-'+i,StudentId:id,StudentName:'Candidate '+i,StudentMajor:'Computer Science',CompanyId:'company-one',OpportunityId:'internship-one',OpportunityTitle:'Software internship',CoverLetter:'Synthetic cover letter for a performance test.',Status:0,SubmittedAt:Date.now()+i}});
 }
 const check=(ok,name)=>{if(!ok)throw Error(name);checks.push(name);};
 const ctx=await page.context().browser().newContext({viewport:{width:1440,height:1000}}),p=await ctx.newPage();
 const errors=[];p.on('pageerror',e=>errors.push(e.message));
 await p.goto(base+'/__fixture.aspx?user=supervisor-one');
 const response=await p.goto(base+'/Pages/Company/Applications.aspx');
 const html=await response.text();
 check(response.status()===200,'Queue renders');
 check(await p.locator('.application-row').count()===12,'All application summaries preserved');
 check(response.headers()['server-timing'].includes('3 calls'),'Initial queue makes only three Firebase calls with cache disabled');
 check(!html.includes('data-details-loaded="true"'),'Initial HTML does not fetch any optional candidate profiles');
 await p.locator('#candidate-perf-app-11 .candidate-panel[data-details-loaded=true]').waitFor();
 check((await p.locator('#candidate-perf-app-11').innerText()).includes('N11'),'First selected profile loads independently');
 check(await p.locator('[data-details-loaded=true]').count()===1,'Only the selected profile is populated');
 check(await p.locator('iframe[src]').count()===0,'PDFs stay deferred');
 await p.locator('[data-application-id=perf-app-5] .review-details-toggle').click();
 await p.locator('#candidate-perf-app-5 [data-details-loaded=true]').waitFor();
 check((await p.locator('#candidate-perf-app-5').innerText()).includes('C#, testing'),'On-demand profile includes skills');
 let repeats=0;p.on('request',r=>{if(r.url().includes('candidate=perf-app-5'))repeats++;});
 await p.locator('[data-application-id=perf-app-11] .review-details-toggle').click();
 await p.locator('[data-application-id=perf-app-5] .review-details-toggle').click();
 check(repeats===0,'Reopening a loaded profile reuses its existing panel');
 const failing='**/Pages/Company/Applications.aspx?candidate=perf-app-0';
 await p.route(failing,r=>r.fulfill({status:500,body:'Simulated failure'}));
 await p.locator('[data-application-id=perf-app-0] .review-details-toggle').click();
 await p.locator('#candidate-perf-app-0 [data-details-status]').filter({hasText:'Could not load'}).waitFor();
 check(await p.locator('#candidate-perf-app-0 [data-load-candidate]').isVisible(),'Failed load retains an accessible retry link');
 check(await p.locator('.application-row').count()===12,'Detail failure does not remove the queue');
 await p.unroute(failing);await p.locator('#candidate-perf-app-0 [data-load-candidate]').click();
 await p.locator('#candidate-perf-app-0 [data-details-loaded=true]').waitFor();
 check((await p.locator('#candidate-perf-app-0').innerText()).includes('N0'),'Retry loads the correct profile');
 await p.locator('.review-pane-actions .review-decision:not([hidden]) .review-reject-toggle').click();
 await p.locator('#candidate-perf-app-0 textarea').fill('Keep my unsaved review notes');
 p.once('dialog',d=>d.dismiss());
 await p.locator('[data-application-id=perf-app-1] .review-details-toggle').click();
 check(await p.locator('[data-application-id=perf-app-0]').evaluate(e=>e.classList.contains('is-selected')),'Unsaved rejection protection retained');
 check(await p.locator('#candidate-perf-app-0 textarea').inputValue()==='Keep my unsaved review notes','Loading preserves unsaved inputs');
 await p.locator('#candidate-perf-app-0 textarea').fill('');
 await p.locator('[data-application-id=perf-app-1] .review-details-toggle').click();
 await p.locator('#candidate-perf-app-1 [data-details-loaded=true]').waitFor();
 await p.locator('.review-pane-actions .review-decision:not([hidden]) .review-accept-button').click();
 await p.waitForURL('**/Applications.aspx');
 check((await (await p.request.get(db+'/applications/perf-app-1.json')).json()).Status===1,'Existing accept postback persists its decision');
 await p.locator('[data-application-id=perf-app-2] .review-details-toggle').click();
 await p.locator('#candidate-perf-app-2 [data-details-loaded=true]').waitFor();
 await p.locator('.review-pane-actions .review-decision:not([hidden]) .review-reject-toggle').click();
 await p.locator('#candidate-perf-app-2 textarea').fill('Synthetic rejection used only for this regression test.');
 await p.locator('#candidate-perf-app-2 .review-reject-button').click();
 await p.waitForURL('**/Applications.aspx');
 check((await (await p.request.get(db+'/applications/perf-app-2.json')).json()).Status===2,'Existing reject postback persists its reason and decision');
 await ctx.addCookies([{name:'uims-lang',value:'ar',url:base}]);
 await p.setViewportSize({width:390,height:844});
 await p.goto(base+'/Pages/Company/Applications.aspx');await p.evaluate(()=>window.UimsTheme.set('dark'));
 if(await p.locator('.review-detail-pane').isVisible())await p.locator('.review-pane-close').click();
 await p.locator('[data-application-id=perf-app-3] .review-details-toggle').click();
 await p.locator('#candidate-perf-app-3 [data-details-loaded=true]').waitFor();
 check(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Arabic Dark phone layout fits');
 check(await p.locator('.review-detail-pane').getAttribute('role')==='dialog','Mobile details keep dialog semantics');
 await p.screenshot({path:'tests/artifacts/application-review-loading-ar-phone.png'});
 const plain=await page.context().browser().newContext({javaScriptEnabled:false}),q=await plain.newPage();
 await q.goto(base+'/__fixture.aspx?user=supervisor-one');await q.goto(base+'/Pages/Company/Applications.aspx');
 await q.locator('#candidate-perf-app-2 summary').click();
 await q.locator('#candidate-perf-app-2 [data-load-candidate]').click();
 check(await q.locator('#candidate-perf-app-2 [data-details-loaded=true]').count()===1,'No-JavaScript details link loads through the same page');
 await q.goto(base+'/__fixture.aspx?user=other-supervisor');
 await q.goto(base+'/Pages/Company/Applications.aspx?candidate=perf-app-2');
 check(await q.locator('.application-row').count()===0,'Forged candidate ID cannot bypass company scoping');
 check(!(await q.locator('body').innerText()).includes('N2'),'Other company receives no profile details');
 await plain.close();await ctx.close();await page.request.post(db+'/__reset');
 check(errors.length===0,'No uncaught page errors');return {passed:checks.length,checks};
}
